"""Sync the model lists of UVR5_NO_UI.ipynb with UVR5-UI's catalog.

UVR5-UI (https://github.com/Eddycrack864/UVR5-UI) keeps the model catalog in
``assets/models.json`` and the top model per stem in ``assets/recommended_models.json``.
Colab forms need literal dropdown lists, so this script writes them into the notebook:

* the ``MODELS`` / ``RECOMMENDED`` dicts of the Installation cell (between the
  ``# >>> MODELS`` and ``# <<< MODELS`` markers),
* the ``model = ... #@param [...]`` dropdown of each separation cell (found by its
  ``ARCH = "<arch>"`` line) and the "Recommended" line of the Roformer cell,
* the ``model_1`` ... ``model_4`` dropdowns of the Ensemble cell.

Dropdown values that are still in the catalog are kept.

Usage:
    python tools/sync_models.py                       # uses ../UVR5-UI/assets/models.json
    python tools/sync_models.py --catalog path/to/models.json
    python tools/sync_models.py --check               # exit 1 if the notebook is out of date
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOK = ROOT / "UVR5_NO_UI.ipynb"
DEFAULT_CATALOG = ROOT.parent / "UVR5-UI" / "assets" / "models.json"

ARCHES = ("roformer", "mdx23c", "mdxnet", "vrarch", "demucs")
ARCH_LABELS = {"roformer": "Roformer", "mdx23c": "MDX23C", "mdxnet": "MDX-NET", "vrarch": "VR Arch", "demucs": "Demucs"}
# Models of the notebook that are not in UVR5-UI's catalog
EXTRA_MODELS = {"demucs": ["drumsep"]}

BEGIN, END = "# >>> MODELS", "# <<< MODELS"
MODEL_LINE = re.compile(r'^(?P<var>model(?:_\d)?) = "(?P<value>[^"]*)" #@param \[.*\]$', re.M)
ARCH_LINE = re.compile(r'^ARCH = "(?P<arch>\w+)"$', re.M)
RECOMMENDED_LINE = re.compile(r"^#@markdown \*\*Recommended:\*\*.*$", re.M)


def load_catalog(catalog_path):
    catalog_path = Path(catalog_path)
    data = json.loads(catalog_path.read_text(encoding="utf-8"))
    if data.get("version") != 2:
        sys.exit(f"Unsupported catalog version in {catalog_path}: {data.get('version')}")
    models = {arch: {} for arch in ARCHES}
    for entry in data["models"]:
        if entry["arch"] not in models:
            sys.exit(f"Unknown architecture {entry['arch']!r} in {catalog_path}")
        models[entry["arch"]][entry["id"]] = entry["filename"]
    recommended_path = catalog_path.with_name("recommended_models.json")
    recommended = {}
    if recommended_path.exists():
        recommended = json.loads(recommended_path.read_text(encoding="utf-8")).get("recommended", {})
    return models, recommended


def param_list(values):
    return json.dumps(values, ensure_ascii=False)


def render_models_block(models, recommended):
    out = [f"{BEGIN} (generated by tools/sync_models.py from UVR5-UI/assets/models.json, do not edit by hand)",
           "MODELS = {"]
    for arch in ARCHES:
        out.append(f'    "{arch}": {{')
        out += [f"        {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}," for k, v in models[arch].items()]
        out.append("    },")
    out.append("}")
    out.append(f"RECOMMENDED = {json.dumps(recommended, ensure_ascii=False)}")
    out.append(END)
    return "\n".join(out)


def sync_cell(source, models, recommended):
    """Return the synced source of a code cell."""
    if BEGIN in source:
        start = source.index(BEGIN)
        end = source.index(END, start) + len(END)
        return source[:start] + render_models_block(models, recommended) + source[end:]

    arch_match = ARCH_LINE.search(source)
    if arch_match:
        arch = arch_match["arch"]
        options = list(models[arch]) + EXTRA_MODELS.get(arch, [])

        def replace(match):
            value = match["value"] if match["value"] in options else options[0]
            if arch == "roformer" and match["value"] not in options:
                value = recommended.get("Instrumental", options[0])
            return f'{match["var"]} = "{value}" #@param {param_list(options)}'

        source = MODEL_LINE.sub(replace, source)
        if arch == "roformer" and recommended:
            line = "#@markdown **Recommended:** " + " · ".join(f"{stem}: `{model}`" for stem, model in recommended.items())
            source = RECOMMENDED_LINE.sub(lambda _: line, source)
        return source

    if "run_ensemble(" in source:
        options = ["None"] + [f"[{ARCH_LABELS[arch]}] {model_id}" for arch in ARCHES for model_id in models[arch]]

        def replace(match):
            value = match["value"] if match["value"] in options else "None"
            return f'{match["var"]} = "{value}" #@param {param_list(options)}'

        return MODEL_LINE.sub(replace, source)
    return source


def to_lines(text):
    parts = text.split("\n")
    return [p + "\n" for p in parts[:-1]] + ([parts[-1]] if parts[-1] else [])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--catalog", default=DEFAULT_CATALOG, help="UVR5-UI assets/models.json")
    parser.add_argument("--notebook", default=NOTEBOOK)
    parser.add_argument("--check", action="store_true", help="only report whether the notebook is up to date")
    args = parser.parse_args()

    models, recommended = load_catalog(args.catalog)
    notebook_path = Path(args.notebook)
    nb = json.loads(notebook_path.read_text(encoding="utf-8"))

    changed = []
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        source = "".join(cell["source"])
        synced = sync_cell(source, models, recommended)
        if synced != source:
            cell["source"] = to_lines(synced)
            changed.append(cell["metadata"].get("id", "?"))

    counts = ", ".join(f"{ARCH_LABELS[a]} {len(models[a])}" for a in ARCHES)
    if not changed:
        print(f"Notebook is up to date ({counts}).")
        return 0
    if args.check:
        print(f"Notebook is out of date, cells to update: {', '.join(changed)}")
        return 1
    notebook_path.write_text(json.dumps(nb, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Updated {len(changed)} cell(s): {', '.join(changed)} ({counts}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
